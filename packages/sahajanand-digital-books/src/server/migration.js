import { SHEETS, getSpreadsheet, getSheet, initDatabase } from './db.js';

/**
 * Convert column letter (A, B, ..., Z, AA, AB) to 0-based index
 */
const colLetterToIndex = (col) => {
  let idx = 0;
  for (let i = 0; i < col.length; i++) {
    idx = idx * 26 + (col.charCodeAt(i) - 64);
  }
  return idx - 1;
};

/**
 * Unescape basic XML entities
 */
const unescapeXml = (str) => {
  if (!str) return '';
  return str
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'");
};

/**
 * Import pre-parsed sheets data (object mapping sheetName -> 2D array of rows)
 * @param {Object} payload { sheetsData: { [sheetName]: rows2D }, clearExisting: boolean }
 */
export const importMigrationSheets = (payload = {}) => {
  try {
    const { sheetsData = {}, clearExisting = true } = payload;
    const ss = getSpreadsheet();
    const results = {};

    // First ensure base sheets and schema exist
    initDatabase();

    for (const [sheetName, rows] of Object.entries(sheetsData)) {
      if (!rows || rows.length === 0) continue;

      let sheet = ss.getSheetByName(sheetName);
      if (!sheet) {
        sheet = ss.insertSheet(sheetName);
      }

      // Incoming rows: row 0 is headers, row 1..N are data
      const incomingHeaders = rows[0];
      const incomingData = rows.slice(1);

      if (clearExisting) {
        // Clear all except keep clean slate
        sheet.clear();
        // Write headers
        sheet.getRange(1, 1, 1, incomingHeaders.length).setValues([incomingHeaders]);
        sheet.getRange(1, 1, 1, incomingHeaders.length).setFontWeight('bold').setBackground('#f1f5f9');
        sheet.setFrozenRows(1);

        if (incomingData.length > 0) {
          // Normalize column widths across all rows
          const colCount = incomingHeaders.length;
          const cleanRows = incomingData.map((row) => {
            const normalized = new Array(colCount).fill('');
            row.forEach((val, idx) => {
              if (idx < colCount) {
                normalized[idx] = val === null || val === undefined ? '' : String(val);
              }
            });
            return normalized;
          });

          sheet.getRange(2, 1, cleanRows.length, colCount).setValues(cleanRows);
        }
        results[sheetName] = incomingData.length;
      } else {
        // Append mode
        if (incomingData.length > 0) {
          const colCount = sheet.getLastColumn() || incomingHeaders.length;
          const startRow = sheet.getLastRow() + 1;
          const cleanRows = incomingData.map((row) => {
            const normalized = new Array(colCount).fill('');
            row.forEach((val, idx) => {
              if (idx < colCount) {
                normalized[idx] = val === null || val === undefined ? '' : String(val);
              }
            });
            return normalized;
          });
          sheet.getRange(startRow, 1, cleanRows.length, colCount).setValues(cleanRows);
          results[sheetName] = cleanRows.length;
        }
      }
    }

    return {
      success: true,
      message: 'Migration data imported successfully',
      importedCounts: results,
    };
  } catch (error) {
    console.error('Error in importMigrationSheets:', error);
    return {
      success: false,
      message: error.toString(),
    };
  }
};

/**
 * Import binary Excel file (.xlsx) uploaded as base64 string
 * @param {Object} payload { base64Data: string, clearExisting: boolean }
 */
export const importExcelFile = (payload = {}) => {
  try {
    const { base64Data, clearExisting = true } = payload;
    if (!base64Data) {
      throw new Error('No Excel file content provided.');
    }

    // Clean base64 header if present (e.g. data:application/vnd.openxmlformats-officedocument...;base64,...)
    const cleanBase64 = base64Data.includes(',') ? base64Data.split(',')[1] : base64Data;
    const bytes = Utilities.base64Decode(cleanBase64);
    const blob = Utilities.newBlob(bytes, 'application/zip');
    const files = Utilities.unzip(blob);

    // 1. Check for shared strings (if generated by Microsoft Excel or LibreOffice)
    let sharedStrings = [];
    const ssFile = files.find((f) => f.getName() === 'xl/sharedStrings.xml');
    if (ssFile) {
      const ssXml = ssFile.getDataAsString();
      const siMatches = ssXml.match(/<si>([\s\S]*?)<\/si>/g) || [];
      sharedStrings = siMatches.map((si) => {
        const textParts = si.match(/<t[^>]*>([\s\S]*?)<\/t>/g) || [];
        return textParts.map((t) => unescapeXml(t.replace(/<[^>]+>/g, ''))).join('');
      });
    }

    // 2. Read workbook.xml to get sheet names and rIds
    const wbFile = files.find((f) => f.getName() === 'xl/workbook.xml');
    if (!wbFile) {
      throw new Error('Invalid Excel file: xl/workbook.xml not found.');
    }
    const wbXml = wbFile.getDataAsString();
    const sheetMatches = wbXml.match(/<sheet\s+[^>]*name="([^"]+)"[^>]*sheetId="([^"]+)"[^>]*r:id="([^"]+)"[^>]*\/?>/g) ||
      wbXml.match(/<sheet\s+[^>]*name="([^"]+)"[^>]*r:id="([^"]+)"[^>]*sheetId="([^"]+)"[^>]*\/?>/g) || [];

    // Parse relationship target map
    const relsFile = files.find((f) => f.getName() === 'xl/_rels/workbook.xml.rels');
    const relsMap = {};
    if (relsFile) {
      const relsXml = relsFile.getDataAsString();
      const relMatches = relsXml.match(/Id="([^"]+)"[^>]*Target="([^"]+)"/g) || [];
      relMatches.forEach((rm) => {
        const idMatch = rm.match(/Id="([^"]+)"/);
        const tgtMatch = rm.match(/Target="([^"]+)"/);
        if (idMatch && tgtMatch) {
          relsMap[idMatch[1]] = tgtMatch[1];
        }
      });
    }

    const parsedSheetsData = {};

    // 3. For each sheet in workbook, extract worksheet XML and parse rows
    sheetMatches.forEach((sTag) => {
      const nameMatch = sTag.match(/name="([^"]+)"/);
      const rIdMatch = sTag.match(/r:id="([^"]+)"/);
      if (!nameMatch || !rIdMatch) return;

      const sheetName = nameMatch[1];
      const rId = rIdMatch[1];
      let targetPath = relsMap[rId] || `worksheets/sheet${rId.replace('rId', '')}.xml`;
      if (!targetPath.startsWith('xl/')) {
        targetPath = 'xl/' + targetPath;
      }

      const wsFile = files.find((f) => f.getName() === targetPath);
      if (!wsFile) return;

      const wsXml = wsFile.getDataAsString();
      const rowMatches = wsXml.match(/<row\s+[^>]*r="(\d+)"[^>]*>([\s\S]*?)<\/row>/g) || [];

      const sheetRows = [];
      rowMatches.forEach((rowTag) => {
        const cellMatches = rowTag.match(/<c\s+[^>]*r="([A-Z]+)(\d+)"([^>]*)>([\s\S]*?)<\/c>/g) || [];
        const rowCells = {};
        let maxCol = 0;

        cellMatches.forEach((cellTag) => {
          const rAttr = cellTag.match(/r="([A-Z]+)(\d+)"/);
          if (!rAttr) return;
          const colLetter = rAttr[1];
          const colIndex = colLetterToIndex(colLetter);
          if (colIndex > maxCol) maxCol = colIndex;

          const isInline = cellTag.includes('t="inlineStr"');
          const isShared = cellTag.includes('t="s"');

          let cellValue = '';
          if (isInline) {
            const tMatch = cellTag.match(/<t[^>]*>([\s\S]*?)<\/t>/);
            if (tMatch) cellValue = unescapeXml(tMatch[1]);
          } else if (isShared) {
            const vMatch = cellTag.match(/<v>(\d+)<\/v>/);
            if (vMatch) {
              const strIdx = parseInt(vMatch[1], 10);
              cellValue = sharedStrings[strIdx] || '';
            }
          } else {
            const vMatch = cellTag.match(/<v>([\s\S]*?)<\/v>/);
            if (vMatch) {
              cellValue = unescapeXml(vMatch[1]);
            }
          }

          rowCells[colIndex] = cellValue;
        });

        const fullRow = [];
        for (let i = 0; i <= maxCol; i++) {
          fullRow.push(rowCells[i] !== undefined ? rowCells[i] : '');
        }
        sheetRows.push(fullRow);
      });

      if (sheetRows.length > 0) {
        parsedSheetsData[sheetName] = sheetRows;
      }
    });

    // 4. Import the parsed sheets into Google Spreadsheet
    return importMigrationSheets({ sheetsData: parsedSheetsData, clearExisting });
  } catch (err) {
    console.error('Error in importExcelFile:', err);
    return {
      success: false,
      message: err.toString(),
    };
  }
};

/**
 * Get row counts and status for all active sheets in the spreadsheet
 */
export const getMigrationStatus = () => {
  try {
    const ss = getSpreadsheet();
    const sheetCounts = {};
    let totalRecords = 0;

    Object.values(SHEETS).forEach((name) => {
      const sheet = ss.getSheetByName(name);
      if (sheet) {
        const rowCount = Math.max(0, sheet.getLastRow() - 1); // exclude header
        sheetCounts[name] = rowCount;
        totalRecords += rowCount;
      } else {
        sheetCounts[name] = 0;
      }
    });

    return {
      success: true,
      spreadsheetName: ss.getName(),
      spreadsheetUrl: ss.getUrl(),
      totalRecords,
      sheetCounts,
    };
  } catch (error) {
    console.error('Error in getMigrationStatus:', error);
    return {
      success: false,
      message: error.toString(),
      sheetCounts: {},
    };
  }
};

/**
 * Reset all sheets to empty tables with schema headers
 */
export const resetDatabase = () => {
  try {
    const ss = getSpreadsheet();
    Object.values(SHEETS).forEach((name) => {
      const sheet = ss.getSheetByName(name);
      if (sheet && sheet.getLastRow() > 1) {
        sheet.getRange(2, 1, sheet.getLastRow() - 1, sheet.getLastColumn()).clearContent();
      }
    });
    // Re-initialize default settings and number series
    initDatabase();
    return { success: true, message: 'All tables cleared and default configuration reset.' };
  } catch (e) {
    return { success: false, message: e.toString() };
  }
};
